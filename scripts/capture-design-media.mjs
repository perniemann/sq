/**
 * Capture journey stills from the running Vite game into public/design-media/.
 * Usage: node scripts/capture-design-media.mjs
 * Requires: npm run dev on :5173
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const OUT = join(ROOT, 'public', 'design-media')
const BASE = process.env.SQ_CAPTURE_URL ?? 'http://localhost:5173/?nobloom'

mkdirSync(OUT, { recursive: true })

async function waitForCanvas(page) {
  await page.waitForSelector('canvas', { timeout: 60000 })
  // Let R3F / Rapier settle
  await page.waitForTimeout(2500)
}

async function getStore(page) {
  return page.evaluate(async () => {
    const mod = await import('/src/stores/gameStore.ts')
    return Boolean(mod.useGameStore)
  })
}

async function setScene(page, patch) {
  await page.evaluate(async (p) => {
    const { useGameStore } = await import('/src/stores/gameStore.ts')
    const s = useGameStore.getState()
    if (p.demoMode != null) s.setDemoMode(p.demoMode)
    if (p.phase) s.setPhase(p.phase)
    if (p.rallyState) s.setRallyState(p.rallyState)
    if (p.canHit != null) s.setCanHit(p.canHit)
    if (p.currentStriker) s.setCurrentStriker(p.currentStriker)
    if (p.pointWinner && p.pointReason) {
      s.setPointResult(p.pointWinner, p.pointReason)
    }
    if (p.clearPoint) s.clearPointResult()
    if (p.score) {
      useGameStore.setState({
        score: p.score,
        matchState: p.matchState ?? useGameStore.getState().matchState,
      })
    }
  }, patch)
  await page.waitForTimeout(800)
}

async function shot(page, name) {
  const path = join(OUT, `${name}.png`)
  await page.screenshot({ path, type: 'png' })
  console.log('wrote', path)
}

async function main() {
  const browser = await chromium.launch({
    headless: true,
    args: [
      '--use-angle=swiftshader',
      '--enable-webgl',
      '--ignore-gpu-blocklist',
    ],
  })
  const page = await browser.newPage({
    viewport: { width: 1280, height: 800 },
    deviceScaleFactor: 1,
  })
  page.on('pageerror', (e) => console.error('pageerror', e.message))

  await page.goto(BASE, { waitUntil: 'domcontentloaded', timeout: 90000 })
  await waitForCanvas(page)
  const ok = await getStore(page)
  if (!ok) throw new Error('gameStore import failed')

  // Idle lockup
  await setScene(page, {
    demoMode: false,
    phase: 'idle',
    rallyState: 'inactive',
    clearPoint: true,
  })
  await shot(page, 'journey-idle')

  // Serve
  await setScene(page, {
    phase: 'serving',
    rallyState: 'inactive',
    canHit: true,
    currentStriker: 'player',
    clearPoint: true,
  })
  await shot(page, 'journey-serve')

  // Rally
  await setScene(page, {
    phase: 'rally',
    rallyState: 'active',
    canHit: true,
    currentStriker: 'player',
    score: { player: 4, opponent: 3 },
    clearPoint: true,
  })
  await shot(page, 'journey-rally')

  // Point callout
  await setScene(page, {
    phase: 'point',
    rallyState: 'inactive',
    pointWinner: 'player',
    pointReason: 'winner',
    score: { player: 5, opponent: 3 },
  })
  await shot(page, 'journey-point')

  // Match over — MatchState requires nested config.gamesToWin
  await setScene(page, {
    phase: 'matchOver',
    rallyState: 'inactive',
    clearPoint: true,
    score: { player: 11, opponent: 7 },
    matchState: {
      gamesWon: { player: 2, opponent: 0 },
      currentGame: 3,
      config: { pointsToWin: 11, mustWinBy: 2, gamesToWin: 2 },
    },
  })
  await shot(page, 'journey-match-over')

  await browser.close()

  writeFileSync(
    join(OUT, 'README.md'),
    [
      '# design-media',
      '',
      'Journey stills for `/design` Play section. Regenerated by:',
      '',
      '```bash',
      'npm run dev   # :5173',
      'node scripts/capture-design-media.mjs',
      '```',
      '',
    ].join('\n'),
    'utf8',
  )
  console.log('done')
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
